# --- DAY 4 ADDITION: Limit Order Book (LOB) Data Structure ---
class LimitOrderBook:
    def __init__(self):
        # Using sorted lists or dicts to track bids (descending) and asks (ascending)
        self.bids = {}  # Price -> List of Orders
        self.asks = {}  # Price -> List of Orders
        print("Initialized Limit Order Book (LOB) state structures.")

    def add_order(self, order_id, price, quantity, side="BUY"):
        """Adds an incoming order into the appropriate book side."""
        book = self.bids if side == "BUY" else self.asks

        if price not in book:
            book[price] = []

        book[price].append({"order_id": order_id, "qty": quantity})
        print(f"Added {side} Order -> ID: {order_id} | Price: {price} | Qty: {quantity}")

    def display_book_summary(self):
        print("\n--- Current Order Book Snapshot ---")
        print("ASKS (Sellers):", sorted(self.asks.keys()))
        print("BIDS (Buyers):", sorted(self.bids.keys(), reverse=True))

