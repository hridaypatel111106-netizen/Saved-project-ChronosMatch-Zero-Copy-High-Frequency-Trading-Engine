import mmap
import struct
import asyncio
import os
import time

print("Initializing ChronosMatch Week 1: Memory-Mapped Ring Buffer & Asyncio Firehose...")

# Define binary structure layout using Python's struct module
# Format: 'I d I' -> Unsigned Int (Order ID), Double (Price), Unsigned Int (Quantity)
STRUCT_FORMAT = 'I d I'
RECORD_SIZE = struct.calcsize(STRUCT_FORMAT)
BUFFER_CAPACITY = 1000  # Number of orders in the ring buffer
TOTAL_BUFFER_SIZE = RECORD_SIZE * BUFFER_CAPACITY

# Create a temporary memory-mapped file for the IPC Ring Buffer
mmap_filename = "chronos_ipc_ring.dat"

# Ensure clean state
if os.path.exists(mmap_filename):
    os.remove(mmap_filename)

with open(mmap_filename, "wb") as f:
    f.write(b'\x00' * TOTAL_BUFFER_SIZE)

# Open memory-mapped file for read/write
with open(mmap_filename, "r+b") as f:
    ipc_buffer = mmap.mmap(f.fileno(), TOTAL_BUFFER_SIZE)

    # Function to write an order directly into the mmap ring buffer (Zero-Copy IPC simulation)
    def write_order_to_ring(index, order_id, price, quantity):
        offset = (index % BUFFER_CAPACITY) * RECORD_SIZE
        packed_data = struct.pack(STRUCT_FORMAT, order_id, price, quantity)
        ipc_buffer.seek(offset)
        ipc_buffer.write(packed_data)

    # Asyncio Market Firehose: simulating incoming Nasdaq/NYSE ticks
    async def market_firehose(num_orders=500):
        print(f"Starting Market Firehose: Blasting mock orders into IPC bus...")
        start_time = time.perf_counter()

        for i in range(num_orders):
            order_id = 1000 + i
            price = round(150.0 + (i % 20) * 0.05, 2)
            quantity = 100 * ((i % 5) + 1)

            # Write to memory-mapped buffer
            write_order_to_ring(i, order_id, price, quantity)

            # Yield control asynchronously to simulate high-frequency streaming
            if i % 100 == 0:
                await asyncio.sleep(0.001)

        end_time = time.perf_counter()
        print(f"Successfully blasted {num_orders} orders into mmap buffer in {(end_time - start_time)*1000:.2f} ms.")

    # Run the asyncio event loop in Colab
    async def main():
        await market_firehose(500)

    # Execute the event loop
    await main()

    # Verify reading back from the mmap buffer
    ipc_buffer.seek(0)
    sample_bytes = ipc_buffer.read(RECORD_SIZE)
    decoded_id, decoded_price, decoded_qty = struct.unpack(STRUCT_FORMAT, sample_bytes)
    print(f"Verification Read from mmap buffer -> Order ID: {decoded_id}, Price: {decoded_price}, Quantity: {decoded_qty}")

    ipc_buffer.close()


# --- DAY 2 ADDITION: Mmap Ring Buffer Consumer ---
def read_orders_from_ring(num_orders_to_read=500):
    print("Starting Ring Buffer Consumer: Reading ticks back from shared memory...")
    read_start_time = time.perf_counter()

    with open("chronos_ipc_ring.dat", "r+b") as f:
        # Re-attach to the existing memory-mapped file
        consumer_buffer = mmap.mmap(f.fileno(), TOTAL_BUFFER_SIZE)

        matched_count = 0
        for i in range(num_orders_to_read):
            offset = (i % BUFFER_CAPACITY) * RECORD_SIZE
            consumer_buffer.seek(offset)
            raw_data = consumer_buffer.read(RECORD_SIZE)

            # Unpack the raw binary bytes back into Python variables (Zero-Copy read)
            oid, oprice, oqty = struct.unpack(STRUCT_FORMAT, raw_data)
            if oid != 0:
                matched_count += 1

        consumer_buffer.close()

    read_end_time = time.perf_counter()
    print(f"Successfully processed {matched_count} orders from zero-copy memory in {((read_end_time - read_start_time)*1000):.4f} ms.")

# Run the consumer reader
read_orders_from_ring(500)

# --- DAY 3 ADDITION: Nanosecond Latency Benchmarker ---
def benchmark_order_latency():
    print("\nRunning Day 3 Task: Nanosecond Round-Trip Latency Benchmark...")

    # Track entry time using high-precision performance counter
    start_ns = time.perf_counter_ns()

    with open("chronos_ipc_ring.dat", "r+b") as f:
        bench_buffer = mmap.mmap(f.fileno(), TOTAL_BUFFER_SIZE)

        # Read a specific slot and measure individual access latency
        offset = 0 # Testing the first order slot
        bench_buffer.seek(offset)
        raw_data = bench_buffer.read(RECORD_SIZE)

        end_ns = time.perf_counter_ns()

        # Unpack order details
        oid, oprice, oqty = struct.unpack(STRUCT_FORMAT, raw_data)

        bench_buffer.close()

    latency_ns = end_ns - start_ns
    latency_us = latency_ns / 1000.0  # Convert to microseconds

    print(f"Benchmark Results -> Order ID: {oid} | Price: {oprice} | Qty: {oqty}")
    print(f"Single-Order Memory Read Latency: {latency_ns} ns ({latency_us:.3f} µs)")

# Run the Day 3 benchmark
benchmark_order_latency()

# --- DAY 4 ADDITION: Limit Order Book (LOB) Data Structure ---
class LimitOrderBook:
    def __init__(self):
        # Using sorted lists or dicts to track bids (descending) and asks (ascending)
        self.bids = {}  # Price -> List of Orders
        self.asks = {}  # Price -> List of Orders
        print("Initialized Limit Order Book (LOB) state structures.")

    def add_order(self, order_id, price, quantity, side="BUY"):
        """Adds an incoming order into the appropriate book side."""
        book = self.bids if side == "BUY" else self.asks

        if price not in book:
            book[price] = []

        book[price].append({"order_id": order_id, "qty": quantity})
        print(f"Added {side} Order -> ID: {order_id} | Price: {price} | Qty: {quantity}")

    def display_book_summary(self):
        print("\n--- Current Order Book Snapshot ---")
        print("ASKS (Sellers):", sorted(self.asks.keys()))
        print("BIDS (Buyers):", sorted(self.bids.keys(), reverse=True))

# Test the LOB structure
lob = LimitOrderBook()
lob.add_order(1001, 150.05, 100, "BUY")
lob.add_order(1002, 150.10, 200, "SELL")
lob.display_book_summary()

# --- DAY 5 TASK: End-to-End IPC to Limit Order Book Integration ---
print("\nRunning Day 5 Task: Integrating mmap Ring Buffer with Limit Order Book...")

# Initialize our Limit Order Book
lob = LimitOrderBook()

# Open the shared mmap ring buffer to read back our blasted orders
with open("chronos_ipc_ring.dat", "r+b") as f:
    integration_buffer = mmap.mmap(f.fileno(), TOTAL_BUFFER_SIZE)

    # Read the first few orders from our buffer and populate the LOB
    processed_count = 0
    for i in range(10):  # Reading first 10 orders as a demonstration
        offset = i * RECORD_SIZE
        integration_buffer.seek(offset)
        raw_data = integration_buffer.read(RECORD_SIZE)

        if len(raw_data) < RECORD_SIZE:
            break

        order_id, price, quantity = struct.unpack(STRUCT_FORMAT, raw_data)

        # Alternate sides just for simulation variety (Even IDs = BUY, Odd IDs = SELL)
        side = "BUY" if order_id % 2 == 0 else "SELL"

        # Add to Limit Order Book
        lob.add_order(order_id, price, quantity, side)
        processed_count += 1

    integration_buffer.close()

print(f"\nSuccessfully transferred {processed_count} orders from shared memory mmap bus into Limit Order Book.")

# Display final integrated book snapshot
lob.display_book_summary()