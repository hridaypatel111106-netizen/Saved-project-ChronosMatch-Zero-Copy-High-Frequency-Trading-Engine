import mmap
import struct
import asyncio
import os
import time

print("Initializing ChronosMatch Week 1: Memory-Mapped Ring Buffer & Asyncio Firehose...")

# Define binary structure layout using Python's struct module
# Format: 'I d I' -> Unsigned Int (Order ID), Double (Price), Unsigned Int (Quantity)
STRUCT_FORMAT = 'I d I'
RECORD_SIZE = struct.calcsize(STRUCT_FORMAT)
BUFFER_CAPACITY = 1000  # Number of orders in the ring buffer
TOTAL_BUFFER_SIZE = RECORD_SIZE * BUFFER_CAPACITY

# Create a temporary memory-mapped file for the IPC Ring Buffer
mmap_filename = "chronos_ipc_ring.dat"

# Ensure clean state
if os.path.exists(mmap_filename):
    os.remove(mmap_filename)

with open(mmap_filename, "wb") as f:
    f.write(b'\x00' * TOTAL_BUFFER_SIZE)

# Open memory-mapped file for read/write
with open(mmap_filename, "r+b") as f:
    ipc_buffer = mmap.mmap(f.fileno(), TOTAL_BUFFER_SIZE)

    # Function to write an order directly into the mmap ring buffer (Zero-Copy IPC simulation)
    def write_order_to_ring(index, order_id, price, quantity):
        offset = (index % BUFFER_CAPACITY) * RECORD_SIZE
        packed_data = struct.pack(STRUCT_FORMAT, order_id, price, quantity)
        ipc_buffer.seek(offset)
        ipc_buffer.write(packed_data)

    # Asyncio Market Firehose: simulating incoming Nasdaq/NYSE ticks
    async def market_firehose(num_orders=500):
        print(f"Starting Market Firehose: Blasting mock orders into IPC bus...")
        start_time = time.perf_counter()

        for i in range(num_orders):
            order_id = 1000 + i
            price = round(150.0 + (i % 20) * 0.05, 2)
            quantity = 100 * ((i % 5) + 1)

            # Write to memory-mapped buffer
            write_order_to_ring(i, order_id, price, quantity)

            # Yield control asynchronously to simulate high-frequency streaming
            if i % 100 == 0:
                await asyncio.sleep(0.001)

        end_time = time.perf_counter()
        print(f"Successfully blasted {num_orders} orders into mmap buffer in {(end_time - start_time)*1000:.2f} ms.")

    # Run the asyncio event loop in Colab
    async def main():
        await market_firehose(500)

    # Execute the event loop
    await main()

    # Verify reading back from the mmap buffer
    ipc_buffer.seek(0)
    sample_bytes = ipc_buffer.read(RECORD_SIZE)
    decoded_id, decoded_price, decoded_qty = struct.unpack(STRUCT_FORMAT, sample_bytes)
    print(f"Verification Read from mmap buffer -> Order ID: {decoded_id}, Price: {decoded_price}, Quantity: {decoded_qty}")

    ipc_buffer.close()