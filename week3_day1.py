# --- WEEK 2 TASK 4: Order Cancellation & Market Depth Analyzer ---
class AdvancedMatchingEngine(MatchingEngine):
    def __init__(self):
        super().__init__()
        # Fast lookup mapping: order_id -> (side, price) for O(1) cancellation tracking
        self.order_lookup = {}

    def add_order(self, order_id, price, quantity, side="BUY"):
        super().add_order(order_id, price, quantity, side)
        # Track location for fast access
        self.order_lookup[order_id] = (side, price)

    def cancel_order(self, order_id):
        """Cancels a resting order from the order book using fast lookup."""
        if order_id not in self.order_lookup:
            print(f"Cancel Failed: Order ID {order_id} not found in active book.")
            return False

        side, price = self.order_lookup[order_id]
        book = self.bids if side == "BUY" else self.asks

        if price in book:
            # Filter out the canceled order from the price queue
            original_len = len(book[price])
            book[price] = [ordr for ordr in book[price] if ordr["order_id"] != order_id]

            if len(book[price]) < original_len:
                print(f"Successfully Canceled {side} Order ID: {order_id} at price {price}")
                del self.order_lookup[order_id]
                # Clean up empty price levels
                if not book[price]:
                    del book[price]
                return True

        print(f"Cancel Error: Order ID {order_id} mismatch in book state.")
        return False

    def get_market_depth(self):
        """Calculates total aggregated volume across bids and asks."""
        total_bid_qty = sum(sum(o['qty'] for o in q) for q in self.bids.values())
        total_ask_qty = sum(sum(o['qty'] for o in q) for q in self.asks.values())
        return total_bid_qty, total_ask_qty

