# --- WEEK 2 TASK 1: Dynamic Trade-Matching Engine ---
class MatchingEngine(LimitOrderBook):
    def __init__(self):
        super().__init__()
        self.trade_history = []
        print("Initialized MatchingEngine execution module.")

    def match_order(self, order_id, price, quantity, side="BUY"):
        """
        Processes incoming orders. Matches crossing prices immediately;
        otherwise, adds remaining quantity to the order book as a resting limit order.
        """
        print(f"\nProcessing Incoming {side} Order -> ID: {order_id} | Price: {price} | Qty: {quantity}")
        remaining_qty = quantity

        if side == "BUY":
            # Match against ASKS (ascending order: lowest price first)
            while remaining_qty > 0 and self.asks:
                best_ask_price = min(self.asks.keys())
                if price >= best_ask_price:  # Price crosses!
                    ask_queue = self.asks[best_ask_price]
                    resting_order = ask_queue[0]

                    match_qty = min(remaining_qty, resting_order["qty"])
                    print(f"  [MATCH] Executed Trade! Buyer {order_id} matched with Seller {resting_order['order_id']} | Qty: {match_qty} @ {best_ask_price}")

                    self.trade_history.append({
                        "buy_id": order_id,
                        "sell_id": resting_order["order_id"],
                        "price": best_ask_price,
                        "qty": match_qty
                    })

                    remaining_qty -= match_qty
                    resting_order["qty"] -= match_qty

                    # Remove resting order if fully filled
                    if resting_order["qty"] == 0:
                        ask_queue.pop(0)
                        if not ask_queue:
                            del self.asks[best_ask_price]
                else:
                    break  # No more matching prices

            # If shares remain, rest on the Bids book
            if remaining_qty > 0:
                self.add_order(order_id, price, remaining_qty, "BUY")

        else:  # SELL order
            # Match against BIDS (descending order: highest price first)
            while remaining_qty > 0 and self.bids:
                best_bid_price = max(self.bids.keys())
                if price <= best_bid_price:  # Price crosses!
                    bid_queue = self.bids[best_bid_price]
                    resting_order = bid_queue[0]

                    match_qty = min(remaining_qty, resting_order["qty"])
                    print(f"  [MATCH] Executed Trade! Seller {order_id} matched with Buyer {resting_order['order_id']} | Qty: {match_qty} @ {best_bid_price}")

                    self.trade_history.append({
                        "sell_id": order_id,
                        "buy_id": resting_order["order_id"],
                        "price": best_bid_price,
                        "qty": match_qty
                    })

                    remaining_qty -= match_qty
                    resting_order["qty"] -= match_qty

                    if resting_order["qty"] == 0:
                        bid_queue.pop(0)
                        if not bid_queue:
                            del self.bids[best_bid_price]
                else:
                    break

            # If shares remain, rest on the Asks book
            if remaining_qty > 0:
                self.add_order(order_id, price, remaining_qty, "SELL")

