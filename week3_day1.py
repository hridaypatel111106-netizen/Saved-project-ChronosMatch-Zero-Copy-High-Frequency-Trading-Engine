# --- WEEK 2 TASK 5: Trade Execution Logging & Fill Reports ---
class FullyLoadedMatchingEngine(AdvancedMatchingEngine):
    def __init__(self):
        super().__init__()
        self.execution_logs = []

    def match_order(self, order_id, price, quantity, side="BUY"):
        """Extended match logic that records detailed execution fill payloads."""
        # Run standard matching logic from parent
        super().match_order(order_id, price, quantity, side)

        # If any trades were generated during this match cycle, log them
        while self.trade_history:
            trade = self.trade_history.pop(0)
            fill_report = {
                "timestamp_ns": time.perf_counter_ns(),
                "buy_id": trade["buy_id"],
                "sell_id": trade["sell_id"],
                "price": trade["price"],
                "qty": trade["qty"]
            }
            self.execution_logs.append(fill_report)
            print(f"  [AUDIT] Fill Report Generated -> Buy ID: {fill_report['buy_id']} | Sell ID: {fill_report['sell_id']} | {fill_report['qty']} @ {fill_report['price']} | Time: {fill_report['timestamp_ns']} ns")

    def display_execution_audit_trail(self):
        print("\n--- Execution Audit Trail Summary ---")
        for idx, log in enumerate(self.execution_logs, 1):
            print(f"Fill #{idx} | Buy: {log['buy_id']} | Sell: {log['sell_id']} | Qty: {log['qty']} | Price: {log['price']} | Timestamp: {log['timestamp_ns']} ns")

